#!/usr/bin/env node
/**
 * Builds the repository's UI projection from the default Recipe.
 *
 * `ui/src/generated/assembly.ts` and the staged Module sources are generated
 * output: the SDK's Assembler writes them from `recipes/default.vivy.yml`, and
 * both the dev server and the Vite build import them. Run this before a
 * typecheck, test, or build so the projection can never be hand-edited into
 * agreement with a stale Recipe.
 *
 *   node scripts/stage-ui-assembly.mjs   # from ui/
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const uiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = resolve(uiRoot, '..');
const recipe = resolve(repositoryRoot, 'recipes/default.vivy.yml');

if (!existsSync(recipe)) {
  console.error(`stage-ui: the default Recipe is missing at ${recipe}`);
  process.exit(1);
}

const result = spawnSync('go', ['run', './sdk', 'stage-ui', '--recipe', recipe, '--out', resolve(uiRoot, 'src/generated')], {
  cwd: repositoryRoot,
  stdio: 'inherit',
});

if (result.error) {
  console.error(`stage-ui: could not run the Vivy SDK (${result.error.message}).`);
  console.error('stage-ui: this build reads its assembled UI projection from the Recipe, so the Go toolchain is required.');
  process.exit(1);
}
if (result.status !== 0) process.exit(result.status ?? 1);

const assembly = resolve(uiRoot, 'src/generated/assembly.ts');
const head = readFileSync(assembly, 'utf8').split('\n', 1)[0];
if (!head.includes('Code generated by vivy-sdk')) {
  console.error(`stage-ui: ${assembly} is not Assembler output; refusing to continue.`);
  process.exit(1);
}