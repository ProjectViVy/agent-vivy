// These constants mirror the public v1 Port catalog. Keeping the identities
// here makes the generated Assembly independent from runtime discovery and
// lets the compiler reject a contribution that is routed to the wrong Host.
const (
	UIExtensionPort = "std/ui-extension@v1"
	UIRootPort      = "std/ui-root@v1"

	UIAssemblyGeneratedMarker = "// Code generated by vivy-sdk. DO NOT EDIT."
)

// These compatibility values are initialized from sdk/ui's embedded
// package.json. Generation itself re-reads the same embedded metadata so a
// supplied Recipe pin cannot drift from the package used by Vite.
var (
	UIAssemblySDKPackageName = uiSDK.PackageName()
	UIAssemblySDKVersion     = uiSDK.Version()
)

// UIAssemblyErrorCode is deliberately closed. Callers can distinguish a
// malformed Recipe from an unavailable build input without parsing text.
type UIAssemblyErrorCode string

const (
	UIAssemblyErrorDuplicateRoot      UIAssemblyErrorCode = "duplicate_root"
	UIAssemblyErrorAmbiguousOrder     UIAssemblyErrorCode = "ambiguous_extension_order"
	UIAssemblyErrorMissingTarget      UIAssemblyErrorCode = "missing_target"
	UIAssemblyErrorFloatingDependency UIAssemblyErrorCode = "floating_dependency"
	UIAssemblyErrorRemoteEntry        UIAssemblyErrorCode = "remote_entry_url"
	UIAssemblyErrorMissingHash        UIAssemblyErrorCode = "missing_hash"
	UIAssemblyErrorInvalidPort        UIAssemblyErrorCode = "invalid_port"
	UIAssemblyErrorDuplicateID        UIAssemblyErrorCode = "duplicate_id"
	UIAssemblyErrorInvalidInput       UIAssemblyErrorCode = "invalid_input"
	UIAssemblyErrorSDKVersionMismatch UIAssemblyErrorCode = "sdk_version_mismatch"
	UIAssemblyErrorRootRelationship   UIAssemblyErrorCode = "root_relationship"
	UIAssemblyErrorConflictingAlias   UIAssemblyErrorCode = "conflicting_alias"
)

// UIAssemblyError names the exact contribution and rule that prevented
// generation. Secret values and filesystem contents are never included.
type UIAssemblyError struct {
	Code         UIAssemblyErrorCode
	Contribution string
	Detail       string
}

func (err *UIAssemblyError) Error() string {
	if err == nil {
		return "<nil>"
	}
	if err.Contribution == "" {
		return fmt.Sprintf("UI Assembly %s: %s", err.Code, err.Detail)
	}
	return fmt.Sprintf("UI Assembly %s (%s): %s", err.Code, err.Contribution, err.Detail)
}

// UIModule is the build-owned description of one selected full-code UI
// contribution. It is not a runtime registry entry. Entry is an explicit,
// package-relative TypeScript import specifier; it may never be a URL or an
// absolute machine path.
//
// ModuleID identifies the source Module for provenance. ID identifies the
// UI Provider exposed by that Module. For the common one-provider-per-module
// case ID may serve as both values.
type UIModule struct {
	ID         string `json:"id,omitempty" yaml:"id,omitempty"`
	ProviderID string `json:"providerId,omitempty" yaml:"providerId,omitempty"`
	ModuleID   string `json:"moduleId,omitempty" yaml:"moduleId,omitempty"`
	Port       string `json:"port,omitempty" yaml:"port,omitempty"`

	// Entry is a normalized ./ import confined to this Module's source tree;
	// package specifiers, URLs, absolute paths, and traversal are rejected.
	Entry      string `json:"entry,omitempty" yaml:"entry,omitempty"`
	ImportPath string `json:"importPath,omitempty" yaml:"importPath,omitempty"`
	Export     string `json:"export,omitempty" yaml:"export,omitempty"`
	ExportName string `json:"exportName,omitempty" yaml:"exportName,omitempty"`

	SourceHash   string `json:"sourceHash,omitempty" yaml:"sourceHash,omitempty"`
	SourceSHA256 string `json:"sourceSha256,omitempty" yaml:"sourceSha256,omitempty"`

	LockHash           string `json:"lockHash,omitempty" yaml:"lockHash,omitempty"`
	DependencyLockHash string `json:"dependencyLockHash,omitempty" yaml:"dependencyLockHash,omitempty"`

	AssetHash      string `json:"assetHash,omitempty" yaml:"assetHash,omitempty"`
	FinalAssetHash string `json:"finalAssetHash,omitempty" yaml:"finalAssetHash,omitempty"`

	// Dependencies are package.json dependency names and exact versions. A
	// lock hash alone does not make a floating package range a safe source
	// input, so ranges are rejected before imports are generated.
	Dependencies        map[string]string `json:"dependencies,omitempty" yaml:"dependencies,omitempty"`
	PackageDependencies map[string]string `json:"packageDependencies,omitempty" yaml:"packageDependencies,omitempty"`

	Before   []string `json:"before,omitempty" yaml:"before,omitempty"`
	After    []string `json:"after,omitempty" yaml:"after,omitempty"`
	Replaces []string `json:"replaces,omitempty" yaml:"replaces,omitempty"`
}

// UIAssemblyInput is the complete, explicit input to the UI generator. The
// generator only reads these values: it does not walk plugin directories,
// invoke a package manager, execute a shell command, or access the network.
type UIAssemblyInput struct {
	SDKVersion string `json:"sdkVersion" yaml:"sdkVersion"`

	// Roots is normally zero or one item. Root is a convenience for callers
	// constructing a single selected root without a slice.
	Root  UIModule   `json:"root,omitempty" yaml:"root,omitempty"`
	Roots []UIModule `json:"roots,omitempty" yaml:"roots,omitempty"`

	Extensions     []UIModule `json:"extensions,omitempty" yaml:"extensions,omitempty"`
	ExtensionOrder []string   `json:"extensionOrder,omitempty" yaml:"extensionOrder,omitempty"`
	// Order is an alias accepted for recipe adapters. Supplying both aliases
	// with different values is rejected as an ambiguous Recipe.
	Order []string `json:"order,omitempty" yaml:"order,omitempty"`

	// These maps allow a Recipe adapter to keep content-addressed inputs in a
	// separate manifest table. Per-module fields take precedence. Entries for
	// omitted Modules are intentionally ignored and never leak into output.
	SourceHashes         map[string]string `json:"sourceHashes,omitempty" yaml:"sourceHashes,omitempty"`
	DependencyLockHashes map[string]string `json:"dependencyLockHashes,omitempty" yaml:"dependencyLockHashes,omitempty"`
	LockHashes           map[string]string `json:"lockHashes,omitempty" yaml:"lockHashes,omitempty"`
	AssetHashes          map[string]string `json:"assetHashes,omitempty" yaml:"assetHashes,omitempty"`
	FinalAssetHashes     map[string]string `json:"finalAssetHashes,omitempty" yaml:"finalAssetHashes,omitempty"`
	// Catalogs is the validated, selected translation projection. It is an
	// explicit compiler input so generated hosts never discover catalogs at
	// runtime and catalog content participates in the sealed UI identity.
	Catalogs []CatalogManifest `json:"catalogs,omitempty" yaml:"catalogs,omitempty"`
}

func cloneUIAssemblyInput(source *UIAssemblyInput) *UIAssemblyInput {
	if source == nil {
		return nil
	}
	cloned := *source
	cloned.Root = cloneUIModule(source.Root)
	cloned.Roots = make([]UIModule, len(source.Roots))
	for index, contribution := range source.Roots {
		cloned.Roots[index] = cloneUIModule(contribution)
	}
	cloned.Extensions = make([]UIModule, len(source.Extensions))
	for index, contribution := range source.Extensions {
		cloned.Extensions[index] = cloneUIModule(contribution)
	}
	// Extension enumeration is not semantic once ExtensionOrder is explicit;
	// canonical Recipe bytes therefore sort this input-only list by stable
	// identity while preserving the separate order sequence.
	sort.SliceStable(cloned.Extensions, func(left, right int) bool {
		leftKey := cloned.Extensions[left].ID + "\x00" + cloned.Extensions[left].ModuleID + "\x00" + cloned.Extensions[left].Entry
		rightKey := cloned.Extensions[right].ID + "\x00" + cloned.Extensions[right].ModuleID + "\x00" + cloned.Extensions[right].Entry
		return leftKey < rightKey
	})
	cloned.ExtensionOrder = append([]string(nil), source.ExtensionOrder...)
	cloned.Order = append([]string(nil), source.Order...)
	cloned.SourceHashes = cloneStringMap(source.SourceHashes)
	cloned.DependencyLockHashes = cloneStringMap(source.DependencyLockHashes)
	cloned.LockHashes = cloneStringMap(source.LockHashes)
	cloned.AssetHashes = cloneStringMap(source.AssetHashes)
	cloned.FinalAssetHashes = cloneStringMap(source.FinalAssetHashes)
	cloned.Catalogs = cloneCatalogManifests(source.Catalogs)
	return &cloned
}

func cloneUIModule(source UIModule) UIModule {
	cloned := source
	cloned.Dependencies = cloneStringMap(source.Dependencies)
	cloned.PackageDependencies = cloneStringMap(source.PackageDependencies)
	cloned.Before = append([]string(nil), source.Before...)
	cloned.After = append([]string(nil), source.After...)
	cloned.Replaces = append([]string(nil), source.Replaces...)
	return cloned
}

// UIAssemblyManifest is the UI projection sealed into a Generation Manifest.
// Maps are keyed by selected Provider ID, and every selected contribution has
// one source, dependency-lock, SDK, and final asset identity.
type UIAssemblyManifest struct {
	Root                 string              `json:"root,omitempty"`
	Extensions           []string            `json:"extensions"`
	Replacements         map[string][]string `json:"replacements,omitempty"`
	SourceHashes         map[string]string   `json:"sourceHashes"`
	DependencyLockHashes map[string]string   `json:"dependencyLockHashes"`
	SDKPackage           string              `json:"sdkPackage"`
	SDKVersion           string              `json:"sdkVersion"`
	AssetHashes          map[string]string   `json:"assetHashes"`
	Catalogs             []CatalogManifest   `json:"catalogs,omitempty"`
}

// Canonical returns stable JSON suitable for inclusion in a content-addressed
// Generation identity. encoding/json sorts map keys; all slices were
// normalized before this manifest is returned.
func (manifest UIAssemblyManifest) Canonical() []byte {
	raw, err := json.Marshal(manifest)
	if err != nil {
		// All fields are strings/maps/slices populated by the generator, so this
		// is unreachable. Returning a deterministic empty object keeps this
		// convenience method total if a caller constructs an invalid value.
		return []byte("{}")
	}
	return raw
}

// UIAssembly is the generated TypeScript module and its sealed provenance.
// Generated and Code are compatibility spellings for build adapters; both
// contain the same immutable bytes as Source.
type UIAssembly struct {
	Source   []byte
	Manifest UIAssemblyManifest

	Generated []byte
	Code      []byte
}

var (
	uiDigestPattern        = regexp.MustCompile(`^[0-9a-f]{64}$`)
	uiCatalogModulePattern = regexp.MustCompile(`^[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?/[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?$`)
	uiSemverPattern        = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?(?:\+[0-9A-Za-z-]+(?:\.[0-9A-Za-z-]+)*)?$`)
	uiDependencyName       = regexp.MustCompile(`^(?:@[^/\s]+/)?[^/\s]+$`)
	uiImportSchemePattern  = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9+.-]*:`)
	uiIdentifierPattern    = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
)

