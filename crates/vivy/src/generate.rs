//! The generated agent package: `Cargo.toml` with the selected crates and
//! `src/main.rs` adding the selected plugins, in recipe order. The shape
//! follows Rig's own launcher (`src/launcher/project.rs` at the pinned rev).

use std::fs;
use std::io;
use std::path::Path;

use crate::recipe::Recipe;

/// The crate every agent is built on: the session, the kernel and the
/// services plugins share.
const HARNESS: &str = "rig-harness";

/// The generated `Cargo.toml`. Plugin crates have their default features
/// off, so only what selected components ask for is compiled in.
/// `recipe_dir` resolves the `path` of a repository crate.
pub fn manifest(recipe: &Recipe, origin: &str, recipe_dir: &Path) -> String {
    let git = quoted(&recipe.rig.git);
    let rev = quoted(&recipe.rig.rev);
    let mut text = format!(
        "# Generated by vivy from {origin}. Do not edit: change the recipe and run `vivy build`.\n\
         [package]\n\
         name = {name}\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         \n\
         # Its own workspace, apart from the Vivy workspace around it.\n\
         [workspace]\n\
         \n\
         [dependencies]\n",
        name = quoted(&recipe.name),
    );
    let crates = recipe.crates();
    // The harness keeps its default features; a component may add more.
    let harness_features = crates
        .get(HARNESS)
        .map(|s| s.features.clone())
        .unwrap_or_default();
    text.push_str(&format!(
        "{HARNESS} = {{ git = {git}, rev = {rev}{} }}\n",
        feature_list(&harness_features)
    ));
    let host = Path::new(env!("CARGO_MANIFEST_DIR")).join("../vivy-process");
    text.push_str(&format!(
        "vivy-process = {{ path = {} }}\n",
        quoted(&host.to_string_lossy())
    ));
    for (krate, selected) in crates.iter().filter(|(krate, _)| **krate != HARNESS) {
        let source = match selected.path {
            Some(path) => format!(
                "path = {}",
                quoted(&recipe_dir.join(path).to_string_lossy())
            ),
            None => format!("git = {git}, rev = {rev}"),
        };
        text.push_str(&format!(
            "{krate} = {{ {source}, default-features = false{} }}\n",
            feature_list(&selected.features)
        ));
    }
    text
}

/// The generated `src/main.rs`: the harness, then each selected plugin
/// through `rig_harness::load`, which records where it came from.
pub fn main_rs(recipe: &Recipe, origin: &str) -> String {
    let rig = format!("git {}?rev={}", recipe.rig.git, recipe.rig.rev);
    let mut text = format!(
        "// Generated by vivy from {origin}. Do not edit: change the recipe and run `vivy build`.\n\
         fn main() -> rig_harness::AppExit {{\n    \
             let session_guard = match vivy_process::session::enter_from_env() {{\n        \
                 Ok(guard) => guard,\n        \
                 Err(error) => {{\n            \
                     eprintln!(\"vivy: session entry failed: {{error}}\");\n            \
                     return rig_harness::AppExit::error();\n        \
                 }}\n    \
             }};\n    \
             let mut app = rig_harness::App::new();\n    \
             if let Some(guard) = &session_guard {{\n        \
                 app.insert_resource(rig_harness::host::session::SessionPaths(\n            \
                     rig_harness::harness_protocol::SessionDir::at(guard.directory.path()),\n        \
                 ));\n    \
             }}\n    \
             // A failing system, observer or command from a plugin is logged.\n    \
             app.set_error_handler(rig_harness::error::warn);\n    \
             app.add_plugins((rig_harness::HeadlessPlugins, rig_harness::RigHarnessPlugins));\n"
    );
    for component in &recipe.components {
        text.push_str(&format!("    // {}\n", component.name));
        let source = match &component.path {
            Some(path) => format!("path {path}"),
            None => rig.clone(),
        };
        for plugin in &component.plugins {
            text.push_str(&format!(
                "    rig_harness::load::<{plugin}>(&mut app, {:?}, {source:?});\n",
                component.krate
            ));
        }
    }
    text.push_str(
        "    // A debug build warns at start about agent-loop systems left unordered.\n    \
         #[cfg(debug_assertions)]\n    \
         rig_harness::check_stages_at_start(&mut app);\n    \
         rig_harness::run(app)\n}\n",
    );
    text
}

/// Writes the package into `directory`. Each file is written only when it
/// changes, so Cargo's fingerprints stay valid.
pub fn write(directory: &Path, recipe: &Recipe, origin: &str, recipe_dir: &Path) -> io::Result<()> {
    write_if_changed(
        &directory.join("Cargo.toml"),
        &manifest(recipe, origin, recipe_dir),
    )?;
    write_if_changed(&directory.join("src/main.rs"), &main_rs(recipe, origin))
}

pub fn write_if_changed(path: &Path, contents: &str) -> io::Result<()> {
    if fs::read_to_string(path).is_ok_and(|current| current == contents) {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, contents)
}

fn feature_list<'a>(features: impl IntoIterator<Item = &'a &'a str>) -> String {
    let features: Vec<String> = features.into_iter().map(|f| quoted(f)).collect();
    if features.is_empty() {
        String::new()
    } else {
        format!(", features = [{}]", features.join(", "))
    }
}

/// A TOML basic string.
fn quoted(text: &str) -> String {
    let mut quoted = String::from("\"");
    for c in text.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            c if c.is_control() => quoted.push_str(&format!("\\u{:04X}", u32::from(c))),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

#[cfg(test)]
mod tests {
    use super::*;

    const RECIPE: &str = "
name: agent
rig: { git: https://example.invalid/rig, rev: abc }
components:
  - name: tools
    crate: rig-basics
    plugins: [rig_basics::coding_tools::ReadTool, rig_basics::coding_tools::ShellTool]
  - name: terminal
    crate: rig-tui
    plugins: [rig_tui::TuiPlugin]
    features: { rig-basics: [tui] }
";

    #[test]
    fn manifest_lists_selected_crates_with_features() {
        let recipe = Recipe::parse(RECIPE).unwrap();
        let text = manifest(&recipe, "recipes/agent.yaml", Path::new("/r"));
        assert!(text.contains("name = \"agent\"\n"));
        assert!(
            text.contains("vivy-process = { path = "),
            "host guard is mandatory"
        );
        assert!(
            text.contains(
                "rig-harness = { git = \"https://example.invalid/rig\", rev = \"abc\" }\n"
            )
        );
        assert!(text.contains(
            "rig-basics = { git = \"https://example.invalid/rig\", rev = \"abc\", default-features = false, features = [\"tui\"] }\n"
        ));
        assert!(text.contains(
            "rig-tui = { git = \"https://example.invalid/rig\", rev = \"abc\", default-features = false }\n"
        ));
    }

    #[test]
    fn removing_a_component_removes_its_crate_and_features() {
        let without = RECIPE.split("  - name: terminal").next().unwrap();
        let recipe = Recipe::parse(without).unwrap();
        let text = manifest(&recipe, "r", Path::new("/r"));
        assert!(!text.contains("rig-tui"));
        assert!(!text.contains("tui"));
        assert!(!main_rs(&recipe, "r").contains("rig_tui"));
    }

    #[test]
    fn repository_crates_come_by_path() {
        let text = RECIPE.replace(
            "crate: rig-tui\n",
            "crate: rig-tui\n    path: ../plugins/tui\n",
        );
        let recipe = Recipe::parse(&text).unwrap();
        let expected = Path::new("/repo/recipes").join("../plugins/tui");
        assert!(
            manifest(&recipe, "r", Path::new("/repo/recipes")).contains(&format!(
                "rig-tui = {{ path = {}, default-features = false }}\n",
                quoted(&expected.to_string_lossy())
            ))
        );
        assert!(main_rs(&recipe, "r").contains("\"rig-tui\", \"path ../plugins/tui\")"));
    }

    #[test]
    fn recipe_cannot_replace_the_host_guard_with_a_plugin_dependency() {
        let text = RECIPE
            .replace("rig-tui", "vivy-process")
            .replace("rig_tui", "vivy_process");
        let error = Recipe::parse(&text).unwrap_err().to_string();
        assert!(
            error.contains("reserved for generated session ownership"),
            "{error}"
        );
    }

    #[test]
    fn main_loads_plugins_in_recipe_order() {
        let recipe = Recipe::parse(RECIPE).unwrap();
        let text = main_rs(&recipe, "r");
        let enter = text
            .find("vivy_process::session::enter_from_env()")
            .expect("guarded entry");
        assert!(enter < text.find("rig_harness::App::new()").unwrap());
        assert!(text.contains("SessionDir::at(guard.directory.path())"));
        let read = text
            .find("load::<rig_basics::coding_tools::ReadTool>")
            .unwrap();
        let shell = text
            .find("load::<rig_basics::coding_tools::ShellTool>")
            .unwrap();
        let tui = text.find("load::<rig_tui::TuiPlugin>(&mut app, \"rig-tui\", \"git https://example.invalid/rig?rev=abc\")").unwrap();
        assert!(read < shell && shell < tui);
        assert!(text.trim_end().ends_with("rig_harness::run(app)\n}"));
    }
}
